num1=int(input("enter the no"))
num2=int(input("enter another no"))
operator=input("enter (+,-,*,/,%)")
if operator=="+":
    print("num1+num2")
elif operator=="-":
    print("num1-num2")
elif operator=="*":
    print("num1*num2")
elif operator=="/":
    print("num1/num2")
elif operator=="%":
    print("num1%num2")
else:
    print("invalid operator")

